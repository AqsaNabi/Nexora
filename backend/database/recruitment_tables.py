
from backend.database.recruitment_db import get_recruitment_connection


# ============================================================
# NEXORA RECRUITMENT DATABASE SCHEMA
# ============================================================

def create_recruitment_tables():

    connection = None
    cursor = None

    try:
        connection = get_recruitment_connection()
        cursor = connection.cursor()

        # ====================================================
        # 1. SEQUENCE FOR RECRUITMENT POSTS
        # ====================================================

        cursor.execute("""
            CREATE SEQUENCE IF NOT EXISTS recruitment_post_id_seq
                START WITH 1
                INCREMENT BY 1;
        """)

        # ====================================================
        # 2. RECRUITMENT POSTS TABLE
        # ====================================================

        cursor.execute("""
            CREATE TABLE IF NOT EXISTS recruitment_posts (
                post_id VARCHAR(20) NOT NULL
                    DEFAULT (
                        'POST-' || LPAD(
                            NEXTVAL('recruitment_post_id_seq')::TEXT,
                            6,
                            '0'
                        )
                    ),

                job_description TEXT NOT NULL,
                original_prompt TEXT,
                job_title VARCHAR(255),

                CONSTRAINT recruitment_posts_pkey
                    PRIMARY KEY (post_id)
            );
        """)

        # ====================================================
        # 3. RECRUITMENT METADATA TABLE
        # ====================================================

        cursor.execute("""
            CREATE TABLE IF NOT EXISTS recruitment_metadata (
                metadata_id BIGINT GENERATED BY DEFAULT AS IDENTITY
                    PRIMARY KEY,

                post_id VARCHAR(20) NOT NULL,
                form_id VARCHAR(255),
                form_url TEXT,

                image_urls JSONB DEFAULT '[]'::JSONB,

                created_at TIMESTAMP WITH TIME ZONE
                    DEFAULT CURRENT_TIMESTAMP,

                updated_at TIMESTAMP WITH TIME ZONE
                    DEFAULT CURRENT_TIMESTAMP,

                question_mapping JSONB DEFAULT '{}'::JSONB,
                application_form JSONB,

                CONSTRAINT recruitment_metadata_post_id_key
                    UNIQUE (post_id),

                CONSTRAINT fk_metadata_post
                    FOREIGN KEY (post_id)
                    REFERENCES recruitment_posts(post_id)
                    ON DELETE CASCADE
            );
        """)

        # ====================================================
        # 4. RECRUITMENT DATA TABLE
        # ====================================================

        cursor.execute("""
            CREATE TABLE IF NOT EXISTS recruitment_data (
                application_id BIGINT GENERATED BY DEFAULT AS IDENTITY
                    PRIMARY KEY,

                post_id VARCHAR(20) NOT NULL,
                full_name VARCHAR(150) NOT NULL,
                email VARCHAR(150) NOT NULL,
                phone VARCHAR(20),

                resume_file BYTEA,
                resume_filename VARCHAR(255),
                resume_content_type VARCHAR(100),

                additional_data JSONB DEFAULT '{}'::JSONB,

                submitted_at TIMESTAMP WITH TIME ZONE
                    DEFAULT CURRENT_TIMESTAMP,

                candidate_score NUMERIC(6,2),

                CONSTRAINT fk_recruitment_post
                    FOREIGN KEY (post_id)
                    REFERENCES recruitment_posts(post_id)
                    ON DELETE CASCADE
            );
        """)

        # ====================================================
        # 5. RECRUITMENT PROCESSED RESPONSES TABLE
        # ====================================================

        cursor.execute("""
            CREATE TABLE IF NOT EXISTS recruitment_processed_responses (
                form_id VARCHAR(255) NOT NULL,
                response_id VARCHAR(255) NOT NULL,

                processed_at TIMESTAMP WITH TIME ZONE
                    DEFAULT CURRENT_TIMESTAMP,

                CONSTRAINT recruitment_processed_responses_pkey
                    PRIMARY KEY (form_id, response_id)
            );
        """)

        # ====================================================
        # 6. INDEXES
        # ====================================================

        cursor.execute("""
            CREATE INDEX IF NOT EXISTS idx_recruitment_data_post_id
                ON recruitment_data(post_id);
        """)

        cursor.execute("""
            CREATE INDEX IF NOT EXISTS idx_recruitment_data_email
                ON recruitment_data(email);
        """)

        cursor.execute("""
            CREATE INDEX IF NOT EXISTS idx_recruitment_metadata_post_id
                ON recruitment_metadata(post_id);
        """)

        connection.commit()

        print("All four recruitment tables created successfully!")

    except Exception as error:

        if connection:
            connection.rollback()

        print(f"Recruitment table creation failed: {error}")
        raise

    finally:

        if cursor:
            cursor.close()

        if connection:
            connection.close()


# ============================================================
# EXECUTE TABLE CREATION
# ============================================================

if __name__ == "__main__":
    create_recruitment_tables()
